CREATE TABLE IF NOT EXISTS klassen (
 id TEXT PRIMARY KEY, name TEXT NOT NULL, tokenHash TEXT NOT NULL UNIQUE,
 createdAt TEXT NOT NULL, aktiv INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS feedback (
 id TEXT PRIMARY KEY, klasseId TEXT NOT NULL REFERENCES klassen(id),
 videoId TEXT NOT NULL, titel TEXT NOT NULL,
 klasse INTEGER NOT NULL CHECK (klasse BETWEEN 1 AND 6),
 schwierigkeit INTEGER NOT NULL CHECK (schwierigkeit BETWEEN 1 AND 3),
 spass INTEGER NOT NULL CHECK (spass BETWEEN 1 AND 3),
 zeit TEXT NOT NULL, audio BLOB, mime TEXT, geloescht INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS feedback_zeit ON feedback(zeit DESC,id DESC);
CREATE INDEX IF NOT EXISTS feedback_klasse_zeit ON feedback(klasseId,zeit DESC,id DESC);
